def conclusion(doc):
    S.add_heading(doc, "8. Conclusion and Future Work", level=1, rule=True)
    S.add_body(doc,
        f"Measured purely on its engineering metrics, Sanad performed reasonably for a first prototype: {AGREEMENT} "
        "agreement between the distress classifier and clinician labels, 91% screening completion, and 88% "
        "user satisfaction. Those are acceptable numbers for an early-stage system. But the finding that "
        "matters is not technical. It is that 79% of the students who used Sanad had never before interacted "
        "with any mental-health resource of any kind. The fact that a four-week pilot of a student project, "
        "built with limited resources and tested on a small sample, reached students like that tells you a "
        "great deal about the size of the gap the existing system leaves open.")
    S.add_body(doc,
        "Sanad will not solve the Egyptian student mental-health crisis, and it does not pretend to. It is one "
        "small tool. What it appears able to do — and what the pilot suggests it is already doing to some "
        "degree — is to serve as a first step for students who would otherwise take no step at all. For a "
        "population in which nine of ten distressed students currently receive nothing, lowering the barrier "
        "to the first contact is not a trivial achievement.")

    S.add_heading(doc, "Future Work", level=2)
    S.add_bullets(doc, [
        "Curate a purpose-built, larger, clinician-labelled dataset of Egyptian student free-text responses to "
        "address the classifier's weak recall on the mild-distress boundary, and use it to benchmark providers "
        "against one another.",
        "Redesign the recommendation module to incorporate Islamic-mindfulness and family-centred strategies "
        "explicitly, the two informal supports Egyptian students most commonly use and the ones pilot "
        "participants asked for.",
        "Add longitudinal tracking so registered users can monitor their scores over time and receive a gentle "
        "alert if their distress level rises across sessions.",
        "Run a randomised controlled trial comparing outcomes between Sanad users and a control group, to move "
        "from promising engagement data toward genuine evidence of clinical benefit.",
        "Explore deployment over WhatsApp, whose penetration in Egypt far exceeds that of standalone web apps, "
        "particularly among lower-income students.",
        "Establish a formal referral partnership with at least one Egyptian university health unit, creating a "
        "structured pathway from anonymous screening to professional care.",
    ])
    S.page_break(doc)


