        "scale put defensible numbers on the problem. Baklola and colleagues surveyed 3,240 undergraduates "
        "across 21 Egyptian universities using proportionate allocation sampling and the Arabic General "
        "Health Questionnaire (AGHQ-28), and reported a 68.1% prevalence of psychological distress. The "
        "global average for comparable student populations sits at roughly 28–30%. The Egyptian figure is "
