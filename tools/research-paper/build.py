        "weight it gives up is returned to the questionnaire. The weighted average is rounded to the nearest "
        "severity level. Two design properties are worth emphasising. First, the questionnaire — the "
        "clinically validated instrument — always dominates, which is the correct ordering of trust. Second, "
        "the fusion is applied conservatively: the merged result is compared against the questionnaire "
        "severity and the higher of the two is kept, so the language model can only ever raise a student's "
        "assessed severity, never lower it. A student whose words betray more distress than their checkbox "
